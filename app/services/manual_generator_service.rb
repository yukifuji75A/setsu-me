class ManualGeneratorService
  POSITIONS = {
    "default" => {
      introduction: [ 1, 3 ],
      analysis: (1..12).to_a
    },
    "friend" => {
      introduction: [ 13, 14, 15, 16, 17, 18 ],
      analysis: (1..18).to_a
    }
  }.freeze

  def initialize(user, theme)
    @user = user
    @theme = theme
  end

  def call
    client = OpenAI::Client.new(access_token: ENV["OPENAI_API_KEY"])

    response = client.chat(
      parameters: {
        model: "gpt-4o-mini",
        response_format: { type: "json_object" },
        messages: [
          { role: "system", content: system_prompt },
          { role: "user", content: user_prompt }
        ]
      }
    )

    result = JSON.parse(response.dig("choices", 0, "message", "content"))
    { basic_spec: result["basic_spec"], handling_guide: result["handling_guide"] }
  end

  private

  def system_prompt
    if @theme == "default"
      <<~PROMPT
        あなたは2種類の文章を生成する専門家です。
        必ず以下のJSON形式のみ返却してください：
        {"basic_spec": "...", "handling_guide": "..."}
      PROMPT
    else
      <<~PROMPT
        あなたは文章を生成する専門家です。
        必ず以下のJSON形式のみ返却してください：
        {"basic_spec": "..."}
      PROMPT
    end
  end

  def user_prompt
    if @theme == "default"
      <<~PROMPT
        以下の指示に従って2種類の文章を生成してください。

        #{basic_spec_prompt}

        ===

        #{handling_guide_prompt}
      PROMPT
    else
      <<~PROMPT
        以下の指示に従って文章を生成してください。

        #{basic_spec_prompt}
      PROMPT
    end
  end

  def basic_spec_prompt
    @theme == "default" ? default_basic_spec_prompt : friend_basic_spec_prompt
  end

  def default_basic_spec_prompt
    <<~PROMPT
      【basic_spec：第1章 製品概要の人物紹介文】

      あなたは「人間を製品に見立てた取扱説明書」を作成する専門のコピーライターです。

      目的：

      この文章は、「人間の取扱説明書」の第1章「製品概要」に掲載される人物紹介文です。

      初めて取扱説明書を読む人が、「本モデルはどのような人物なのか」を短時間で理解できるよう、その人物らしさを簡潔にまとめてください。

      分析方法：

      ・単一の回答だけを取り上げるのではなく、複数の回答を組み合わせて人物像を分析する

      ・性格、価値観、コミュニケーション、思考、行動などの回答に共通する傾向を探す

      ・一見すると異なる回答や意外な組み合わせがある場合は、それらがどのように両立しているのかを考える

      ・回答から直接分かる特徴だけでなく、「なぜそのような行動や考え方をしやすいのか」まで、入力情報から合理的に推測できる範囲で一段深く考察する

      ・分析した内容の中から、この人物を理解するうえで特に重要な特徴を選んで文章化する

      ・回答を一問ずつ説明したり、選択肢をそのまま並べたりしない

      内容：

      ・性格、価値観、コミュニケーションの特徴を中心にまとめる

      ・趣味や好きなものは、人物らしさを補足できる場合のみ自然に含める

      ・MBTI・思考タイプ・行動タイプは参考情報の一つとして扱い、それだけで人物像を決めつけない

      ・「この人はこういう性格」と単純に分類するだけではなく、その性格がどのような考え方や行動につながりやすいのかを意識する

      ・すべての情報を使用する必要はない。人物像を表現するために有効な情報を選び、自然な文章にする

      ・入力内容から合理的に推測できない性格、過去の経験、価値観などを創作しない

      ・推測を事実として断定しない

      ・誇張や創作はしない

      条件：

      ・120〜160文字程度

      ・第三者視点で書く

      ・「本モデル」「この人物」など、取扱説明書らしい表現を自然に使用する

      ・家電製品の取扱説明書をイメージした、客観的で読みやすい文体にする

      ・です・ます調で書く

      ・堅苦しくなりすぎず、読み手が人物像をイメージしやすい自然な文章にする

      ・一つのまとまった文章として書く

      ・箇条書きは禁止

      ・余計な説明や前置きは出力しない

      ・性別を示す表現（「彼」「彼女」「男性」「女性」など）は使用しない

      出力例：

      本モデルは穏やかで周囲との調和を大切にしながらも、自分なりの考えを持って行動するタイプです。人との距離感には慎重な一面がありますが、信頼関係ができると自然体で関われるようになります。無理に周囲へ合わせるより、自分が納得できる環境で力を発揮しやすい人物です。

      ユーザー情報：
      #{introduction_lines}
    PROMPT
  end

  def friend_basic_spec_prompt
    <<~PROMPT
      【basic_spec：友だち向けトリセツ・第1章】

      あなたは、友だちに共有する「自分専用のトリセツ」を作成するコピーライターです。

      目的：
      この文章は、友だちに共有する「友だち向けトリセツ」の第1章に掲載する人物紹介文です。

      回答内容から、この人物が友だちとしてどのような付き合い方をする人なのかを読み取り、文章を読んだ友だちが「この人とはどんなふうに付き合えそうか」「仲良くなるとどんな感じなのか」を自然にイメージできる文章を作成してください。

      単なる性格紹介や回答内容の要約ではなく、複数の回答を関連付けて、この人物らしい友だち付き合いの特徴を一つの文章として表現してください。

      文章の雰囲気：
      ・この人物自身が、友だちに自分のことを教えているような文章にする
      ・友だち同士で話すような、自然で親しみやすい言葉を使う
      ・「〜だよ」「〜しやすいよ」「〜すると、こんな一面も見えてくるよ」などの口語表現を自然に使用する
      ・敬語や堅苦しい表現は使用しない
      ・説明書、業務文書、心理分析レポートのような淡々とした文章にしない
      ・「本モデル」「仕様」「運用」「適しています」など、一般的な製品説明書を連想させる硬い表現は使用しない
      ・少しだけユーモアや親しみを感じられる表現を入れてもよい
      ・馴れ馴れしすぎたり、幼稚な文章になったりしない

      内容：
      ・友だちとしての付き合い方が最も伝わる内容を優先する
      ・仲良くなるまでの距離感と、仲良くなった後の変化を必要に応じて関連付ける
      ・連絡頻度、遊ぶ頻度、直前のお誘いへの反応、誘う・誘われる傾向などから、友だちとの付き合いやすいペースを読み取る
      ・一人の時間と友だちとの時間のバランスから、心地よい距離感を読み取る
      ・悩み相談への希望、意見が違ったときの対応、友だち関係で大切にしていることから、友だちとの関わり方を読み取る
      ・「仲良くなるとこうなります」の回答は、親しくなった後の人物像を表現するために積極的に活用する
      ・好きなものや遊びの情報が与えられている場合、それを性格の根拠として無理に分析せず、友だちと一緒に楽しめることを表現するために必要な場合のみ使用する
      ・回答を一問ずつ説明したり、選択肢をそのまま並べたりしない
      ・提供された情報をすべて文章に含める必要はない
      ・友だちとしての人物像を表現するうえで重要な情報を優先し、文章として自然につながる情報だけを使用する
      ・情報を無理に詰め込んで、単なる回答の羅列にならないようにする
      ・文字数を満たすためだけに不要な情報を追加しない
      ・回答から明確に読み取れない性格や価値観を推測して断定しない
      ・MBTIなどの情報がある場合も、それだけを根拠に人物像を決めつけない
      ・誇張や創作はしない

      条件：
      ・100〜140文字程度
      ・一つのまとまった文章として書く
      ・友だち本人から説明されているような自然な文章にする
      ・文章の流れを重視し、複数の回答を自然に関連付ける
      ・箇条書きは禁止
      ・マークダウン記法は禁止
      ・余計な説明や前置きは出力しない
      ・性別を示す表現（「彼」「彼女」「男性」「女性」など）は使用しない

      出力例：
      無理に距離を縮めるより、自然なペースで仲良くなるタイプだよ。連絡や遊ぶ頻度もお互いに無理のないくらいがちょうどいい。仲良くなると会話も増えて、気を許した相手にはだんだん素の一面が見えてくるよ。

      ユーザー情報：
      #{introduction_lines}
    PROMPT
  end

  def handling_guide_prompt
    <<~PROMPT
      【handling_guide：自己分析レポート】

      あなたは、ユーザーの回答を多角的に分析し、本人の特徴や考え方を言語化する自己分析レポートの専門家です。

      目的：
      以下のユーザー情報をもとに、本人が自分自身について新たな気づきを得られる自己分析レポートを作成してください。

      単に回答内容を要約したり、選択肢から分かりやすい性格を当てはめたりするのではなく、複数の回答を組み合わせ、それぞれの回答がどのようにつながっているのかを考察してください。

      「回答から直接分かること」だけで終わらず、回答同士の共通点・整合性・ギャップ・一見矛盾する組み合わせに注目し、そこから考えられる価値観や考え方、行動パターンまで、入力情報から合理的に導ける範囲で1段、必要に応じて2段程度深く推論してください。

      【分析手順】

      文章を作成する前に、以下の順序でユーザー情報を分析してください。

      1. 各回答から明確に読み取れる特徴や傾向を整理する。

      2. 複数の回答を組み合わせ、「複数の回答に共通して表れている特徴は何か」「別々に見える回答にどのようなつながりがあるか」を探す。

      3. 回答同士の整合性を確認する。複数の回答が同じ方向性を示している場合は、それをその人物の一貫した考え方や行動パターンとして分析する。

      4. 一見すると矛盾している回答や、意外な組み合わせがある場合は特に注目する。どちらか一方を無視したり、単に「矛盾している」と結論づけたりせず、「どのような考え方や条件なら、この2つの特徴が両立するのか」を考察する。

      5. 分析結果を、
         「回答 → 特徴・傾向 → 背景にありそうな価値観や考え方 → 行動への表れ」
         の流れで整理する。回答から導ける範囲で、1段、必要に応じて2段まで深く推論する。

      6. 分析した内容の中から、その人物を理解するうえで特に重要で、複数の回答によって裏付けられている特徴を優先して文章化する。

      【分析における重要なルール】

      ・回答を一問ずつ説明しない
      ・選択肢をそのまま言い換えて並べない
      ・「○○を選んでいるため、○○な性格です」という単純な分析だけで終わらせない
      ・単一の回答だけから人物像を決めつけない
      ・複数の回答から共通する傾向を見つける
      ・回答同士の整合性や一貫性を重視する
      ・一見矛盾する回答や意外な組み合わせから、その背景を考察する
      ・「なぜその選択をするのか」という背景を、他の回答との関係から考える
      ・回答から合理的に導ける範囲で1〜2段深く推論する
      ・推論した内容は事実として断定せず、「〜と考えられます」「〜という傾向がありそうです」などの表現を使う
      ・入力情報に存在しない過去の経験、家庭環境、トラウマ、心理的原因などを創作しない
      ・心理診断や医学的な診断を行わない
      ・MBTI、思考タイプ、行動タイプは参考情報の一つとして扱い、それだけで人物像を決めつけない
      ・趣味や好きなものは、それだけを性格の根拠にしない。他の回答とつながる場合に、人物像を理解する材料として活用する
      ・すべてのユーザー情報を使用する必要はない。分析に有効な情報を選び、不要な情報は無理に文章へ入れない
      ・文字数を満たすためだけに不要な情報や推測を追加しない

      【出力構成】

      以下の5つのセクションで構成してください。

      ①【あなたの特徴】

      性格ワード、MBTI、思考タイプ、行動タイプなどを参考にしながら、

      複数の回答を組み合わせ、この人物の中心的な特徴や行動パターンを分析してください。

      単純な性格紹介ではなく、「この人はどのような考え方をしやすいのか」まで掘り下げてください。

      ②【人との関わり方】

      相性のいいタイプ、嬉しい接し方、苦手なタイプ、苦手な接し方などを組み合わせ、

      人との距離感やコミュニケーションの特徴を分析してください。

      「どのような人と合うか」だけでなく、「なぜそのような関わり方を心地よく感じるのか」まで考察してください。

      ③【心地よく過ごすために】

      落ち着く環境、苦手な環境、知っておいてほしい状況、

      その状況で嬉しい接し方などを組み合わせ、

      この人物が安心して過ごしたり、自分らしく行動したりするために重要な条件を分析してください。

      苦手なことを単に列挙するのではなく、「何が負担になりやすいのか」「どのような配慮があると過ごしやすいのか」まで考察してください。

      ④【あなたらしさが表れるところ】

      趣味、好きな話題、性格、思考、行動、人との関わり方などを横断して分析し、

      この人物らしさが日常の具体的な行動や場面にどのように表れそうかを言語化してください。

      単なる長所の列挙や趣味の紹介にはしないでください。

      ⑤【AIからのメッセージ】

      ここまでの分析を踏まえ、本人に向けたメッセージを書いてください。

      一般的な励ましや、誰にでも当てはまる内容にはしないでください。

      この人物の回答から見えてきた特徴や考え方を一つ以上取り上げ、

      「自分では気づきにくいけれど、実はこういうところがあなたらしい」

      と思えるような内容にしてください。

      【セクションの書き方】

      ・5つのセクションは、それぞれ独立したカードとして表示されることを想定してください
      ・他のセクションを読まなくても、そのセクションだけで内容が理解できるようにしてください
      ・各セクションでは、そのテーマについて特に重要な分析を1〜2個選び、それを複数の回答から裏付ける形で文章化してください
      ・1つのセクションに情報を詰め込みすぎず、主題を明確にしてください
      ・セクション間で同じ分析内容を繰り返さないでください
      ・各セクションは単なる回答の説明ではなく、分析結果を一つのまとまった文章として読めるようにしてください
      ・1文を長くしすぎず、1文の中に複数の異なる内容を詰め込みすぎないでください
      ・話題が大きく切り替わる場合は、自然な改行を1回入れて構いません

      【文字数】

      ・全体で800〜1,000文字程度を目安としてください
      ・内容に応じて各セクションの文字数は柔軟に増減させてください
      ・各セクションは160〜220文字程度を一つの目安としますが、厳密に揃える必要はありません
      ・重要な分析が多いセクションは長めに、情報が少ないセクションは短めにしてください
      ・文字数を満たすために不要な情報や推測を追加しないでください
      ・全体として1,100文字程度を大きく超えないようにしてください

      【文章の条件】

      ・第二者視点で書く（「あなたは〜です」「〜な傾向があります」など）
      ・客観性を保ちながら、本人が読んで前向きになれる温かみのある文章にする
      ・分析結果を押し付けるような断定的な表現は避ける
      ・抽象的な性格表現だけで終わらず、可能な範囲で具体的な行動や場面につなげる
      ・全体を通して同じ内容を繰り返さない
      ・箇条書きは禁止
      ・マークダウン記法（#・*・**など）は使用しない
      ・余計な説明や前置きは出力しない
      ・性別を示す表現（「彼」「彼女」「男性」「女性」など）は使用しない

      ・各セクションの冒頭には必ず「【あなたの特徴】」「【人との関わり方】」「【心地よく過ごすために】」「【あなたらしさが表れるところ】」「【AIからのメッセージ】」のいずれかを付けてください
      ・セクションとセクションの間は必ず改行コード\nを2つ挿入して区切ってください

      ユーザー情報：
      #{analysis_lines}
    PROMPT
  end

  def introduction_lines
    common = answers_for(:common, positions: [ 1, 2, 3, 4, 5 ])
    theme_answers = answers_for(@theme, positions: POSITIONS[@theme][:introduction])
    format_lines(common + theme_answers)
  end

  def analysis_lines
    common = answers_for(:common, positions: [ 1, 2, 3, 4, 5 ])
    theme_answers = answers_for(@theme, positions: POSITIONS[@theme][:analysis])
    format_lines(common + theme_answers)
  end

  def answers_for(theme, positions:)
    @user.answers
         .for_theme(theme)
         .merge(Question.where(position: positions))
         .sort_by { |a| a.question.position }
  end

  def format_lines(answers)
    answers.map do |answer|
      value = answer.question.selection? ? answer.question_option&.label : answer.body
      "#{answer.question.title}：#{value}"
    end.join("\n")
  end
end
